import { bareChrome, renderPreviewCore } from "./renderer.js"
import type { RenderPreviewInput, RenderPreviewOutput } from "./renderer.js"
import type { MapBlock, SourceRange } from "@elef/work-model"

/** Offsets use the original source's UTF-16 code units, including CRLF. */
export interface ProjectionNode {
  readonly id: string
  readonly range: SourceRange
  readonly contentRange: SourceRange
  readonly kind: string
}

export interface SourceProjection extends RenderPreviewOutput {
  readonly revision: number
  readonly nodes: readonly ProjectionNode[]
}

/**
 * Reader projection with inert source annotations. No authoring controls or
 * editable HTML are introduced. Pagination may clone a node into fragments:
 * each fragment retains its node id, range and revision; ids are data values,
 * never DOM ids. A consumer must reject a snapshot from an obsolete revision.
 */
export function renderSourceProjection(input: RenderPreviewInput, revision: number): SourceProjection {
  if (!Number.isSafeInteger(revision) || revision < 0) {
    throw new RangeError("Projection revision must be a nonnegative safe integer.")
  }
  const nodes: ProjectionNode[] = []
  function attributes(mapped: MapBlock | null | undefined): string {
    if (!mapped) return ""
    nodes.push({
      id: mapped.id,
      range: { ...mapped.source_range },
      contentRange: { ...mapped.content_range },
      kind: mapped.kind
    })
    // Map ids are generated by work-model. Escape even these internal values
    // so this seam remains safe if the id vocabulary changes later.
    const id = mapped.id.replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("<", "&lt;")
    return ` data-source-node="${id}" data-source-start="${mapped.source_range.start}" data-source-end="${mapped.source_range.end}" data-source-revision="${revision}"`
  }
  const preview = renderPreviewCore(input, {
    chrome: {
      ...bareChrome,
      documentBlockAttributes: (block) => bareChrome.documentBlockAttributes(block) + attributes(block.mapped),
      presentationBlockAttributes: ({ mapped }) => attributes(mapped),
      slideBlock: ({ className, attributes: sourceAttributes, content, revealEvent }) =>
        `<div class="${className}"${sourceAttributes}${revealEvent === undefined ? "" : ` data-elef-reveal-event="${revealEvent}"`}>${content}</div>`
    }
  })
  return { ...preview, revision, nodes }
}
